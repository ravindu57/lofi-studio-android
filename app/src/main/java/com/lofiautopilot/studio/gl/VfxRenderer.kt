/**
 * Renders one frame: picture (or video frame) -> camera -> effect stack -> screen/encoder.
 * Must be used from a single thread that owns a current GL ES 3 context.
 */
class VfxRenderer(val width: Int, val height: Int) {
    private class Prog(val id: Int) {
        val loc = HashMap<String, Int>()
        fun u(name: String): Int = loc.getOrPut(name) { GLES30.glGetUniformLocation(id, name) }
    }

    private val quad: FloatBuffer = ByteBuffer.allocateDirect(8 * 4).order(ByteOrder.nativeOrder()).asFloatBuffer().apply {
        put(floatArrayOf(-1f, -1f, 1f, -1f, -1f, 1f, 1f, 1f)); position(0)
    }
    private var vao = 0
    private var vbo = 0
    private val texA = IntArray(2)
    private val fbo = IntArray(2)
    private var specTex = 0
    private var waveTex = 0
    /** A picture source. Slot 0 is the clip on screen; slot 1 holds the outgoing clip while a transition runs. */
    private class Slot {
        var tex = 0
        var w = 1
        var h = 1
        var external = false
        val mat = FloatArray(16).also { android.opengl.Matrix.setIdentityM(it, 0) }
        /** Built-in intro id when this slot is generated by a shader instead of a texture. */
        var gen: String? = null
        var genT = 0f
        var genLen = 5f
        var titleTex = 0
        val valid: Boolean get() = tex != 0 || gen != null
    }
    private val slots = arrayOf(Slot(), Slot())
    private val fboT = IntArray(2)
    private val texT = IntArray(2)
    private val genProgs = HashMap<String, Prog?>()
    private val transProgs = HashMap<String, Prog?>()

    /** The transition to draw this frame: id and eased progress 0..1. Set by the frame source before [render]. */
    var transition: Pair<String, Float>? = null

    private var srcProg: Prog? = null
    private var srcExtProg: Prog? = null
    private var blit: Prog? = null
    private val fxProgs = HashMap<String, Prog?>()
    private val textTextures = HashMap<String, Int>()
    private val pBuf = FloatArray(8)

    var palette: Palette = Palette.DEFAULT
        private set
    var look: Look = Look()
    /** Layers whose shaders failed to compile, with the driver's message (shown in the debug screen). */
    val compileErrors = LinkedHashMap<String, String>()
    private val tmpHsv = FloatArray(3)

    fun init() {
        val b = IntArray(1)
        val a = IntArray(1)
        GLES30.glGenVertexArrays(1, a, 0); vao = a[0]
        GLES30.glGenBuffers(1, b, 0); vbo = b[0]
        GLES30.glBindVertexArray(vao)
        GLES30.glBindBuffer(GLES30.GL_ARRAY_BUFFER, vbo)
        GLES30.glBufferData(GLES30.GL_ARRAY_BUFFER, 8 * 4, quad, GLES30.GL_STATIC_DRAW)
        GLES30.glEnableVertexAttribArray(0)
        GLES30.glVertexAttribPointer(0, 2, GLES30.GL_FLOAT, false, 0, 0)
        for (i in 0..1) {
            texA[i] = GlUtil.tex2d(width, height)
            fbo[i] = GlUtil.fbo(texA[i])
        }
        specTex = GlUtil.tex2d(BANDS, 1, GLES30.GL_R8)
        waveTex = GlUtil.tex2d(WAVE_N, 1, GLES30.GL_R8)
        srcProg = Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.source(false)))
        blit = Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.BLIT))
    }

    // ---------- source ----------

    private fun freeSlotTex(sl: Slot) {
        if (sl.tex != 0) GLES30.glDeleteTextures(1, intArrayOf(sl.tex), 0)
        sl.tex = 0; sl.external = false; sl.gen = null
    }

    fun setImage(bmp: Bitmap, slot: Int = 0) {
        val sl = slots[slot]
        freeSlotTex(sl)
        val t = IntArray(1)
        GLES30.glGenTextures(1, t, 0)
        sl.tex = t[0]
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, sl.tex)
        GLUtils.texImage2D(GLES30.GL_TEXTURE_2D, 0, bmp, 0)
        GLES30.glGenerateMipmap(GLES30.GL_TEXTURE_2D)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_MIN_FILTER, GLES30.GL_LINEAR_MIPMAP_LINEAR)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_MAG_FILTER, GLES30.GL_LINEAR)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_WRAP_S, GLES30.GL_CLAMP_TO_EDGE)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_WRAP_T, GLES30.GL_CLAMP_TO_EDGE)
        sl.w = bmp.width; sl.h = bmp.height
        if (slot == 0) palette = Palette.from(bmp)
    }

    /** Creates the OES texture a SurfaceTexture can render video frames into. */
    fun createExternalTexture(): Int {
        val t = IntArray(1)
        GLES30.glGenTextures(1, t, 0)
        GLES30.glBindTexture(GLES11Ext.GL_TEXTURE_EXTERNAL_OES, t[0])
        GLES30.glTexParameteri(GLES11Ext.GL_TEXTURE_EXTERNAL_OES, GLES30.GL_TEXTURE_MIN_FILTER, GLES30.GL_LINEAR)
        GLES30.glTexParameteri(GLES11Ext.GL_TEXTURE_EXTERNAL_OES, GLES30.GL_TEXTURE_MAG_FILTER, GLES30.GL_LINEAR)
        GLES30.glTexParameteri(GLES11Ext.GL_TEXTURE_EXTERNAL_OES, GLES30.GL_TEXTURE_WRAP_S, GLES30.GL_CLAMP_TO_EDGE)
        GLES30.glTexParameteri(GLES11Ext.GL_TEXTURE_EXTERNAL_OES, GLES30.GL_TEXTURE_WRAP_T, GLES30.GL_CLAMP_TO_EDGE)
        if (srcExtProg == null) srcExtProg = Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.source(true)))
        return t[0]
    }

    fun useExternal(texId: Int, w: Int, h: Int, slot: Int = 0) {
        val sl = slots[slot]
        if (sl.tex != texId) freeSlotTex(sl)
        sl.tex = texId; sl.w = w; sl.h = h; sl.external = true; sl.gen = null
    }

    fun setExternalMatrix(m: FloatArray, slot: Int = 0) { System.arraycopy(m, 0, slots[slot].mat, 0, 16) }

    /** Makes a slot show a built-in intro, drawn by its shader. */
    fun useGenerated(introId: String, lenS: Float, slot: Int = 0) {
        val sl = slots[slot]
        freeSlotTex(sl)
        sl.gen = introId; sl.genLen = lenS
    }

    fun setGenTime(slot: Int, t: Float) { slots[slot].genT = t }

    /** The title shown on an intro (white text on transparent). */
    fun setTitle(slot: Int, bmp: Bitmap?) {
        val sl = slots[slot]
        if (sl.titleTex != 0) { GLES30.glDeleteTextures(1, intArrayOf(sl.titleTex), 0); sl.titleTex = 0 }
        if (bmp == null) return
        val t = IntArray(1)
        GLES30.glGenTextures(1, t, 0)
        sl.titleTex = t[0]
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, sl.titleTex)
        GLUtils.texImage2D(GLES30.GL_TEXTURE_2D, 0, bmp, 0)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_MIN_FILTER, GLES30.GL_LINEAR)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_MAG_FILTER, GLES30.GL_LINEAR)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_WRAP_S, GLES30.GL_CLAMP_TO_EDGE)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_WRAP_T, GLES30.GL_CLAMP_TO_EDGE)
    }

    fun clearSlot(slot: Int) {
        val sl = slots[slot]
        freeSlotTex(sl)
        if (sl.titleTex != 0) { GLES30.glDeleteTextures(1, intArrayOf(sl.titleTex), 0); sl.titleTex = 0 }
    }

    fun slotValid(slot: Int) = slots[slot].valid

    /** Swaps what slot 0 and slot 1 hold (the incoming clip becomes the outgoing one without reloading). */
    fun swapSlots() { val t = slots[0]; slots[0] = slots[1]; slots[1] = t }

    fun setPalette(p: Palette) { palette = p }

    // ---------- frame ----------

    fun render(timeS: Float, f: FrameFeatures, targetFbo: Int, targetW: Int, targetH: Int, textFor: ((Layer) -> String)? = null) {
        GLES30.glBindVertexArray(vao)
        GLES30.glDisable(GLES30.GL_BLEND)
        GLES30.glDisable(GLES30.GL_DEPTH_TEST)

        // upload audio textures
        GLES30.glPixelStorei(GLES30.GL_UNPACK_ALIGNMENT, 1)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE1)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, specTex)
        GLES30.glTexSubImage2D(GLES30.GL_TEXTURE_2D, 0, 0, 0, BANDS, 1, GLES30.GL_RED, GLES30.GL_UNSIGNED_BYTE, ByteBuffer.wrap(f.spec))
        GLES30.glActiveTexture(GLES30.GL_TEXTURE2)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, waveTex)
        GLES30.glTexSubImage2D(GLES30.GL_TEXTURE_2D, 0, 0, 0, WAVE_N, 1, GLES30.GL_RED, GLES30.GL_UNSIGNED_BYTE, ByteBuffer.wrap(f.wave))

        // active layers + camera
        val cam = FxCamera.Cam()
        val passes = ArrayList<Pair<Layer, FxDef>>()
        for (layer in look.layers) {
            if (!layer.on) continue
            val def = EffectLibrary.byId[layer.fx] ?: continue
            val win = windowFactor(layer, timeS)
            if (win <= 0f) continue
            val inten = layer.intensity * (if (layer.follow) f.direction else 1f) * win
            if (def.kind == FxKind.CAMERA) {
                FxCamera.apply(cam, layer, def, timeS, reactSignal(layer, f), inten)
            } else if (inten > 0.001f && layer.opacity > 0.001f) {
                passes.add(layer to def)
            }
        }

        // pass 0: source -> buffer 0 (two sources and a transition shader while changing clip)
        GLES30.glViewport(0, 0, width, height)
        val tr = transition
        if (tr != null && slots[1].valid && slots[0].valid && drawTransition(tr, cam, f, timeS)) {
            // done
        } else {
            GLES30.glBindFramebuffer(GLES30.GL_FRAMEBUFFER, fbo[0])
            drawSlot(slots[0], cam, look.fit, f)
        }

        var cur = 0
        for ((layer, def) in passes) {
            val prog = programFor(def) ?: continue
            val out = 1 - cur
            GLES30.glBindFramebuffer(GLES30.GL_FRAMEBUFFER, fbo[out])
            GLES30.glUseProgram(prog.id)
            bindEffect(prog, layer, def, timeS, f, cur, textFor)
            GLES30.glDrawArrays(GLES30.GL_TRIANGLE_STRIP, 0, 4)
            cur = out
        }

        // final blit to the target
        GLES30.glBindFramebuffer(GLES30.GL_FRAMEBUFFER, targetFbo)
        GLES30.glViewport(0, 0, targetW, targetH)
        val b = blit!!
        GLES30.glUseProgram(b.id)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE0)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, texA[cur])
        GLES30.glUniform1i(b.u("uSrc"), 0)
        GLES30.glDrawArrays(GLES30.GL_TRIANGLE_STRIP, 0, 4)
    }

    private fun windowFactor(l: Layer, t: Float): Float {
        if (t < l.from) return 0f
        if (l.to >= 0f && t > l.to) return 0f
        val fadeIn = if (l.from > 0f) ((t - l.from) / 0.6f).coerceIn(0f, 1f) else 1f
        val fadeOut = if (l.to >= 0f) ((l.to - t) / 0.6f).coerceIn(0f, 1f) else 1f
        return minOf(fadeIn, fadeOut)
    }

    private fun reactSignal(l: Layer, f: FrameFeatures): Float {
        val s = when (l.react) {
            React.OFF -> 0f
            React.BASS -> f.bass
            React.MID -> f.mid
            React.HIGH -> f.high
            React.ENERGY -> f.energy
            React.BEAT -> f.beat
        }
        return s * l.reactAmt * 1.6f
    }

    private fun drawSlot(sl: Slot, cam: FxCamera.Cam, fit: Fit, f: FrameFeatures) {
        if (sl.gen != null) { drawGenerated(sl, f); return }
        if (sl.tex == 0) { GLES30.glClearColor(0f, 0f, 0f, 1f); GLES30.glClear(GLES30.GL_COLOR_BUFFER_BIT); return }
        val ext = sl.external
        val p = if (ext) srcExtProg!! else srcProg!!
        GLES30.glUseProgram(p.id)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE0)
        if (ext) GLES30.glBindTexture(GLES11Ext.GL_TEXTURE_EXTERNAL_OES, sl.tex)
        else GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, sl.tex)
        GLES30.glUniform1i(p.u("uImg"), 0)
        GLES30.glUniform2f(p.u("uOut"), width.toFloat(), height.toFloat())
        GLES30.glUniform2f(p.u("uImgSize"), sl.w.toFloat(), sl.h.toFloat())
        GLES30.glUniform4f(p.u("uCam"), cam.scale.coerceAtLeast(0.2f), cam.rot, cam.tx, cam.ty)
        GLES30.glUniform1i(p.u("uFit"), if (fit == Fit.CONTAIN_BLUR) 1 else 0)
        GLES30.glUniform1i(p.u("uFlip"), if (ext) 0 else 1)
        val m = if (ext) sl.mat else IDENTITY
        GLES30.glUniformMatrix4fv(p.u("uTexMat"), 1, false, m, 0)
        GLES30.glDrawArrays(GLES30.GL_TRIANGLE_STRIP, 0, 4)
    }

    private fun drawGenerated(sl: Slot, f: FrameFeatures) {
        val id = sl.gen ?: return
        val prog = genProgs.getOrPut(id) {
            val def = Intros.byId[id] ?: return@getOrPut null
            try { Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.intro(def))) } catch (e: ShaderException) {
                Log.e("VfxRenderer", "Intro $id failed: ${e.message}"); compileErrors["intro:$id"] = e.message ?: "compile error"; null
            }
        } ?: run { GLES30.glClearColor(0f, 0f, 0f, 1f); GLES30.glClear(GLES30.GL_COLOR_BUFFER_BIT); return }
        GLES30.glUseProgram(prog.id)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE1)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, specTex)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE2)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, waveTex)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE3)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, if (sl.titleTex != 0) sl.titleTex else specTex)
        GLES30.glUniform1i(prog.u("uSpec"), 1)
        GLES30.glUniform1i(prog.u("uWave"), 2)
        GLES30.glUniform1i(prog.u("uTitle"), 3)
        GLES30.glUniform1f(prog.u("uHasTitle"), if (sl.titleTex != 0) 1f else 0f)
        GLES30.glUniform1f(prog.u("uTime"), sl.genT)
        GLES30.glUniform1f(prog.u("uLen"), sl.genLen)
        GLES30.glUniform1f(prog.u("uAsp"), width.toFloat() / height)
        GLES30.glUniform1f(prog.u("uBass"), f.bass)
        GLES30.glUniform1f(prog.u("uMid"), f.mid)
        GLES30.glUniform1f(prog.u("uHigh"), f.high)
        GLES30.glUniform1f(prog.u("uEnergy"), f.energy)
        GLES30.glUniform1f(prog.u("uBeat"), f.beat)
        GLES30.glDrawArrays(GLES30.GL_TRIANGLE_STRIP, 0, 4)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE0)
    }

    private fun ensureTransitionBuffers() {
        if (texT[0] != 0) return
        for (i in 0..1) { texT[i] = GlUtil.tex2d(width, height); fboT[i] = GlUtil.fbo(texT[i]) }
    }

    /** Draws outgoing + incoming clips into scratch buffers and mixes them into buffer 0. Returns false if the shader is unusable. */
    private fun drawTransition(tr: Pair<String, Float>, cam: FxCamera.Cam, f: FrameFeatures, timeS: Float): Boolean {
        val def = Transitions.get(tr.first) ?: return false
        val prog = transProgs.getOrPut(def.id) {
            try { Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.transition(def))) } catch (e: ShaderException) {
                Log.e("VfxRenderer", "Transition ${def.id} failed: ${e.message}"); compileErrors["transition:${def.id}"] = e.message ?: "compile error"; null
            }
        } ?: return false
        ensureTransitionBuffers()
        GLES30.glBindFramebuffer(GLES30.GL_FRAMEBUFFER, fboT[0])
        drawSlot(slots[1], cam, look.fit, f)
        GLES30.glBindFramebuffer(GLES30.GL_FRAMEBUFFER, fboT[1])
        drawSlot(slots[0], cam, look.fit, f)
        GLES30.glBindFramebuffer(GLES30.GL_FRAMEBUFFER, fbo[0])
        GLES30.glUseProgram(prog.id)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE0)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, texT[0])
        GLES30.glActiveTexture(GLES30.GL_TEXTURE1)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, texT[1])
        GLES30.glUniform1i(prog.u("uA"), 0)
        GLES30.glUniform1i(prog.u("uB"), 1)
        GLES30.glUniform1f(prog.u("uProg"), Transitions.ease(tr.second))
        GLES30.glUniform1f(prog.u("uTime"), timeS)
        GLES30.glUniform1f(prog.u("uAsp"), width.toFloat() / height)
        GLES30.glUniform1f(prog.u("uBeat"), f.beat)
        GLES30.glUniform1f(prog.u("uBass"), f.bass)
        GLES30.glDrawArrays(GLES30.GL_TRIANGLE_STRIP, 0, 4)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE0)
        return true
    }

    private fun programFor(def: FxDef): Prog? = fxProgs.getOrPut(def.id) {
        try {
            Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.fragment(def)))
        } catch (e: ShaderException) {
            Log.e("VfxRenderer", "Shader ${def.id} failed: ${e.message}")
            compileErrors[def.id] = e.message ?: "compile error"
            null
        }
    }

    private fun toRgb(c: Int, out: FloatArray) {
        out[0] = Color.red(c) / 255f; out[1] = Color.green(c) / 255f; out[2] = Color.blue(c) / 255f
    }

    private val c1 = FloatArray(3)
    private val c2 = FloatArray(3)
    private val pa = FloatArray(3)
    private val pb = FloatArray(3)
    private val pc = FloatArray(3)

    private fun bindEffect(p: Prog, layer: Layer, def: FxDef, t: Float, f: FrameFeatures, srcIdx: Int, textFor: ((Layer) -> String)?) {
        GLES30.glActiveTexture(GLES30.GL_TEXTURE0)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, texA[srcIdx])
        GLES30.glActiveTexture(GLES30.GL_TEXTURE1)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, specTex)
        GLES30.glActiveTexture(GLES30.GL_TEXTURE2)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, waveTex)
        GLES30.glUniform1i(p.u("uSrc"), 0)
        GLES30.glUniform1i(p.u("uSpec"), 1)
        GLES30.glUniform1i(p.u("uWave"), 2)
        GLES30.glUniform2f(p.u("uRes"), width.toFloat(), height.toFloat())
        GLES30.glUniform1f(p.u("uAsp"), width.toFloat() / height)
        GLES30.glUniform1f(p.u("uTime"), t)
        GLES30.glUniform1f(p.u("uBass"), f.bass)
        GLES30.glUniform1f(p.u("uMid"), f.mid)
        GLES30.glUniform1f(p.u("uHigh"), f.high)
        GLES30.glUniform1f(p.u("uEnergy"), f.energy)
        GLES30.glUniform1f(p.u("uBeat"), f.beat)
        GLES30.glUniform1f(p.u("uPhase"), f.phase)
        val win = windowFactor(layer, t)
        GLES30.glUniform1f(p.u("uI"), layer.intensity * (if (layer.follow) f.direction else 1f))
        GLES30.glUniform1f(p.u("uR"), reactSignal(layer, f))
        GLES30.glUniform1f(p.u("uOp"), layer.opacity * win)
        GLES30.glUniform1f(p.u("uSeed"), (layer.id.hashCode() and 0xFFFF) / 65535f)
        for (i in 0 until 8) pBuf[i] = def.params.getOrNull(i)?.let { layer.param(def, it.key) } ?: 0f
        GLES30.glUniform1fv(p.u("uP[0]"), 8, pBuf, 0)
        toRgb(layer.c1 ?: palette.accent, c1)
        toRgb(layer.c2 ?: palette.secondary, c2)
        GLES30.glUniform3fv(p.u("uC1"), 1, c1, 0)
        GLES30.glUniform3fv(p.u("uC2"), 1, c2, 0)
        toRgb(palette.accent, pa); toRgb(palette.secondary, pb); toRgb(palette.light, pc)
        GLES30.glUniform3fv(p.u("uPal0"), 1, pa, 0)
        GLES30.glUniform3fv(p.u("uPal1"), 1, pb, 0)
        GLES30.glUniform3fv(p.u("uPal2"), 1, pc, 0)
        GLES30.glUniform1i(p.u("uKind"), if (def.kind == FxKind.OVERLAY) 1 else 0)
        GLES30.glUniform1i(p.u("uBlend"), layer.blend.ordinal)
    }

    /** Reads the last rendered frame of the given FBO (used for thumbnails). */
    fun readPixels(fboId: Int, w: Int, h: Int): Bitmap {
        val buf = ByteBuffer.allocateDirect(w * h * 4).order(ByteOrder.nativeOrder())
        GLES30.glBindFramebuffer(GLES30.GL_FRAMEBUFFER, fboId)
        GLES30.glReadPixels(0, 0, w, h, GLES30.GL_RGBA, GLES30.GL_UNSIGNED_BYTE, buf)
        val bmp = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888)
        // flip vertically
        val row = IntArray(w)
        val ib = buf.asIntBuffer()
        val out = IntArray(w * h)
        ib.get(out)
        val flipped = IntArray(w * h)
        for (y in 0 until h) {
            System.arraycopy(out, (h - 1 - y) * w, row, 0, w)
            for (x in 0 until w) {
                val v = row[x]
                // RGBA bytes read as little-endian int: 0xAABBGGRR -> ARGB
                flipped[y * w + x] = (v and 0xFF00FF00.toInt()) or ((v and 0xFF) shl 16) or ((v shr 16) and 0xFF)
            }
        }
        bmp.setPixels(flipped, 0, w, 0, 0, w, h)
        return bmp
    }

    fun release() {
        runCatching {
            GLES30.glDeleteTextures(texA.size, texA, 0)
            GLES30.glDeleteFramebuffers(fbo.size, fbo, 0)
            GLES30.glDeleteTextures(2, intArrayOf(specTex, waveTex), 0)
            for (i in 0..1) { clearSlot(i) }
            if (texT[0] != 0) { GLES30.glDeleteTextures(2, texT, 0); GLES30.glDeleteFramebuffers(2, fboT, 0) }
            genProgs.values.forEach { it?.let { p -> GLES30.glDeleteProgram(p.id) } }
            transProgs.values.forEach { it?.let { p -> GLES30.glDeleteProgram(p.id) } }
            fxProgs.values.forEach { it?.let { p -> GLES30.glDeleteProgram(p.id) } }
            srcProg?.let { GLES30.glDeleteProgram(it.id) }
            srcExtProg?.let { GLES30.glDeleteProgram(it.id) }
            blit?.let { GLES30.glDeleteProgram(it.id) }
            GLES30.glDeleteBuffers(1, intArrayOf(vbo), 0)
            GLES30.glDeleteVertexArrays(1, intArrayOf(vao), 0)
        }
        fxProgs.clear(); genProgs.clear(); transProgs.clear()
    }

    /** Compile every effect once so broken shaders are found early (used by the self-test). */
    fun compileAll(): Map<String, String> {
        for (d in EffectLibrary.all) if (d.kind != FxKind.CAMERA) programFor(d)
        for (t in Transitions.all) { runCatching { transProgs.getOrPut(t.id) { Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.transition(t))) } }.onFailure { compileErrors["transition:${t.id}"] = it.message ?: "compile error" } }
        for (i in Intros.all) { runCatching { genProgs.getOrPut(i.id) { Prog(GlUtil.program(ShaderSrc.VERTEX, ShaderSrc.intro(i))) } }.onFailure { compileErrors["intro:${i.id}"] = it.message ?: "compile error" } }
        return compileErrors
    }

